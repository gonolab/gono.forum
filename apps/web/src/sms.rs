pub const SETTING: &str = "login.providers";
/// Delivery methods (`SmsProvider::transport`).
pub const TRANSPORTS: &[&str] = &["local", "aliyun"];

/// The delivery methods and their names in this request's language, in the order of [`TRANSPORTS`].
pub fn transports() -> Vec<(&'static str, &'static str)> {
    let t = crate::i18n::current();
    vec![
        ("local", t.account_manage_transport_local()),
        ("aliyun", t.account_manage_transport_aliyun()),
    ]
}
const ALIYUN_HOST: &str = "dypnsapi.aliyuncs.com";
const ALIYUN_ACTION: &str = "SendSmsVerifyCode";
const ALIYUN_VERSION: &str = "2017-05-25";
const ALIYUN_TIMEOUT: Duration = Duration::from_secs(10);
const RESPONSE_LIMIT: usize = 64 * 1024;
/// SHA-256 of an empty request body.
const EMPTY_SHA256: &str = "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855";
/// RFC 3986: only letters, digits and `-_.~` are left unencoded (required by the canonical query string of
/// Alibaba Cloud signing).
const RFC3986: &AsciiSet = &NON_ALPHANUMERIC
    .remove(b'-')
    .remove(b'_')
    .remove(b'.')
    .remove(b'~');

type Result<T> = anyhow::Result<T>;

/// Errors the admin form can show directly (required fields, format, key configuration), kept apart from
/// internal errors such as database errors.
#[derive(Debug)]
pub struct FormError(pub &'static str);

impl fmt::Display for FormError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(self.0)
    }
}

impl std::error::Error for FormError {}

fn form(condition: bool, message: &'static str) -> Result<()> {
    if condition {
        Ok(())
    } else {
        Err(FormError(message).into())
    }
}

/// The AccessKey Secret is encrypted with the private config `[common] encryption_key` ([`crate::secrets`],
/// the same key as the mail authorization code).
fn encrypt(config: &CommonConfig, secret: &str, context: &[u8]) -> Result<Vec<u8>> {
    config
        .seal(secret, context)
        .ok_or_else(|| FormError(crate::secrets::missing_key()).into())
}

fn decrypt(config: &CommonConfig, encrypted: &[u8], context: &[u8]) -> Result<String> {
    config
        .open(encrypted, context)
        .ok_or_else(|| FormError(crate::i18n::current().account_manage_error_decrypt()).into())
}

/// SMS provider configuration (without the secret).
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(default)]
pub struct SmsProvider {
    /// One of [`TRANSPORTS`].
    pub transport: String,
    pub access_key_id: String,
    /// The platform's preset signature name and template CODE (see "SMS Authentication" in the phone number
    /// verification service console).
    pub sign_name: String,
    pub template_code: String,
    #[serde(skip)]
    pub has_secret: bool,
}

impl Default for SmsProvider {
    fn default() -> Self {
        Self {
            transport: "local".into(),
            access_key_id: String::new(),
            sign_name: String::new(),
            template_code: String::new(),
            has_secret: false,
        }
    }
}

impl SmsProvider {
    fn validate(&self) -> Result<()> {
        form(
            TRANSPORTS.contains(&self.transport.as_str()),
            crate::i18n::current().account_manage_error_transport(),
        )?;
        if self.transport == "aliyun" {
            form(
                (1..=64).contains(&self.access_key_id.len())
                    && self
                        .access_key_id
                        .bytes()
                        .all(|b| b.is_ascii_alphanumeric()),
                crate::i18n::current().account_manage_error_access_key_id(),
            )?;
            form(
                (1..=40).contains(&self.sign_name.chars().count())
                    && !self.sign_name.chars().any(char::is_control),
                crate::i18n::current().account_manage_error_sign_name(),
            )?;
            form(
                (1..=40).contains(&self.template_code.len())
                    && self
                        .template_code
                        .bytes()
                        .all(|b| b.is_ascii_alphanumeric() || b == b'_'),
                crate::i18n::current().account_manage_error_template_code(),
            )?;
        }
        Ok(())
    }

    /// Associated data of the secret: changing the AccessKey ID makes the old ciphertext undecryptable.
    fn context(&self) -> Vec<u8> {
        serde_json::to_vec(&(SETTING, "sms", &self.access_key_id)).expect("serializable context")
    }
}

#[derive(Clone, Default, Serialize, Deserialize)]
#[serde(default)]
struct Stored {
    revision: i64,
    sms: SmsProvider,
    sms_secret: Vec<u8>,
    google: OAuthApp,
    google_secret: Vec<u8>,
    github: OAuthApp,
    github_secret: Vec<u8>,
}

impl Stored {
    fn oauth(&self, provider: Provider) -> (&OAuthApp, &Vec<u8>) {
        match provider {
            Provider::Google => (&self.google, &self.google_secret),
            Provider::Github => (&self.github, &self.github_secret),
        }
    }

    fn oauth_mut(&mut self, provider: Provider) -> (&mut OAuthApp, &mut Vec<u8>) {
        match provider {
            Provider::Google => (&mut self.google, &mut self.google_secret),
            Provider::Github => (&mut self.github, &mut self.github_secret),
        }
    }
}

/// Configuration shown on the admin page (for the secret, only whether it is set).
#[derive(Clone, Debug, Default)]
pub struct Providers {
    pub revision: i64,
    pub sms: SmsProvider,
    pub google: OAuthApp,
    pub github: OAuthApp,
}

impl Providers {
    pub fn oauth(&self, provider: Provider) -> &OAuthApp {
        match provider {
            Provider::Google => &self.google,
            Provider::Github => &self.github,
        }
    }
}

/// Input for saving Google or GitHub credentials in the admin area: an empty Client ID disables the provider
/// and clears the secret; an empty `secret` keeps the old value.
pub struct OAuthInput {
    pub revision: i64,
    pub provider: Provider,
    pub client_id: String,
    pub secret: String,
}

/// Associated data of the Client Secret: changing the Client ID makes the old ciphertext undecryptable.
fn oauth_context(provider: Provider, client_id: &str) -> Vec<u8> {
    serde_json::to_vec(&(SETTING, provider.value(), client_id)).expect("serializable context")
}

/// Input saved in the admin area: an empty `secret` keeps the old value.
pub struct SmsInput {
    pub revision: i64,
    pub sms: SmsProvider,
    pub secret: String,
}

fn decode(row: Option<&db::DbRow>) -> Result<Stored> {
    let Some(row) = row else {
        return Ok(Stored::default());
    };
    serde_json::from_str(&db::text(row, "svalue")?)
        .map_err(|_| anyhow!("malformed sign-in provider configuration"))
}

fn summary(stored: Stored) -> Providers {
    let mut sms = stored.sms;
    sms.has_secret = !stored.sms_secret.is_empty();
    let mut google = stored.google;
    google.has_secret = !stored.google_secret.is_empty();
    let mut github = stored.github;
    github.has_secret = !stored.github_secret.is_empty();
    Providers {
        revision: stored.revision,
        sms,
        google,
        github,
    }
}

async fn stored(db: &Database) -> Result<Stored> {
    let row = db::query("SELECT svalue FROM gonof_common_settings WHERE skey=?")
        .bind(SETTING)
        .fetch_optional(db.executor())
        .await?;
    decode(row.as_ref())
}

/// Read for the admin page (administrators): read-only, checks the administrator through the pool and opens
/// no write transaction.
pub async fn read(db: &Database, actor: Actor) -> std::result::Result<Providers, IdentityError> {
    crate::runtime::admin_unlocked(db, actor).await?;
    Ok(summary(stored(db).await?))
}

/// Read outside the admin area: looks at the delivery method before sending.
pub async fn current(db: &Database) -> Result<Providers> {
    Ok(summary(stored(db).await?))
}

fn candidate(config: &CommonConfig, input: SmsInput, current: &Stored) -> Result<Stored> {
    if input.revision != current.revision {
        return Err(
            IdentityError::Conflict(crate::i18n::current().account_manage_error_stale()).into(),
        );
    }
    let mut next = current.clone();
    let mut sms = input.sms;
    for field in [
        &mut sms.access_key_id,
        &mut sms.sign_name,
        &mut sms.template_code,
    ] {
        *field = field.trim().to_owned();
    }
    sms.has_secret = false;
    sms.validate()?;
    let secret = input.secret.trim();
    let sms_secret = if secret.is_empty() {
        if current.sms_secret.is_empty() {
            Vec::new()
        } else {
            form(
                sms.access_key_id == current.sms.access_key_id,
                crate::i18n::current().account_manage_error_access_key_changed(),
            )?;
            current.sms_secret.clone()
        }
    } else {
        form(
            secret.len() <= 128 && !secret.chars().any(char::is_control),
            crate::i18n::current().account_manage_error_access_secret(),
        )?;
        encrypt(config, secret, &sms.context())?
    };
    if sms.transport == "aliyun" {
        form(
            !sms_secret.is_empty(),
            crate::i18n::current().account_manage_error_access_secret_missing(),
        )?;
        decrypt(config, &sms_secret, &sms.context())?;
    }
    next.revision = current.revision + 1;
    next.sms = sms;
    next.sms_secret = sms_secret;
    Ok(next)
}

fn oauth_candidate(config: &CommonConfig, input: OAuthInput, current: &Stored) -> Result<Stored> {
    if input.revision != current.revision {
        return Err(
            IdentityError::Conflict(crate::i18n::current().account_manage_error_stale()).into(),
        );
    }
    let provider = input.provider;
    let client_id = input.client_id.trim().to_owned();
    let secret = input.secret.trim();
    let mut next = current.clone();
    next.revision = current.revision + 1;
    let (old_app, old_secret) = current.oauth(provider);
    let (app, stored_secret) = next.oauth_mut(provider);
    if client_id.is_empty() {
        // Disable: clear the Client ID and the secret.
        *app = OAuthApp::default();
        stored_secret.clear();
        return Ok(next);
    }
    form(
        client_id.len() <= 255 && client_id.bytes().all(|b| b.is_ascii_graphic()),
        crate::i18n::current().account_manage_error_client_id(),
    )?;
    let encrypted = if secret.is_empty() {
        form(
            !old_secret.is_empty(),
            crate::i18n::current().account_manage_error_client_secret_missing(),
        )?;
        form(
            old_app.client_id == client_id,
            crate::i18n::current().account_manage_error_client_id_changed(),
        )?;
        old_secret.clone()
    } else {
        form(
            secret.len() <= 255 && !secret.chars().any(char::is_control),
            crate::i18n::current().account_manage_error_client_secret(),
        )?;
        encrypt(config, secret, &oauth_context(provider, &client_id))?
    };
    decrypt(config, &encrypted, &oauth_context(provider, &client_id))?;
    *app = OAuthApp {
        client_id,
        has_secret: false,
    };
    *stored_secret = encrypted;
    Ok(next)
}

/// Saves Google or GitHub credentials in the admin area.
pub async fn save_oauth(
    db: &Database,
    config: &CommonConfig,
    actor: Actor,
    input: OAuthInput,
) -> std::result::Result<Providers, IdentityError> {
    let provider = input.provider;
    save_with(
        db,
        actor,
        |current| oauth_candidate(config, input, current),
        |next| {
            serde_json::json!({"revision": next.revision, "provider": provider.value(),
            "configured": !next.oauth(provider).1.is_empty()})
        },
    )
    .await
}

/// Configured Google or GitHub credentials: the Client ID and the decrypted Client Secret. `None` when not
/// configured; an error when the secret cannot be decrypted.
pub async fn oauth_credentials(
    db: &Database,
    config: &CommonConfig,
    provider: Provider,
) -> Result<Option<(String, String)>> {
    let stored = stored(db).await?;
    let (app, secret) = stored.oauth(provider);
    if app.client_id.is_empty() || secret.is_empty() {
        return Ok(None);
    }
    let plain = config
        .open(secret, &oauth_context(provider, &app.client_id))
        .ok_or_else(|| {
            anyhow!(
                "the {} Client Secret cannot be decrypted: check [common] encryption_key in the private configuration or save it again in the admin area",
                provider.label()
            )
        })?;
    Ok(Some((app.client_id.clone(), plain)))
}

/// Saves the SMS provider configuration in the admin area.
pub async fn save_sms(
    db: &Database,
    config: &CommonConfig,
    actor: Actor,
    input: SmsInput,
) -> std::result::Result<Providers, IdentityError> {
    save_with(
        db,
        actor,
        |current| candidate(config, input, current),
        |next| serde_json::json!({"revision": next.revision, "sms_transport": next.sms.transport}),
    )
    .await
}

/// Steps shared by saves of this row: administrator check, queueing, reading the current value, computing the
/// new value, writing and auditing.
async fn save_with(
    db: &Database,
    actor: Actor,
    change: impl FnOnce(&Stored) -> Result<Stored>,
    audit: impl FnOnce(&Stored) -> serde_json::Value,
) -> std::result::Result<Providers, IdentityError> {
    let mut tx = db.begin_write().await?;
    crate::runtime::admin_locked(db, &mut tx, actor).await?;
    // The first save and later changes are both queued (like `mail.transport`).
    db::query(
        "SELECT skey FROM gonof_common_settings WHERE skey='identity.bootstrap_admin' FOR UPDATE",
    )
    .fetch_one(db.observe(&mut *tx))
    .await?;
    let row = db::query("SELECT svalue FROM gonof_common_settings WHERE skey=? FOR UPDATE")
        .bind(SETTING)
        .fetch_optional(db.observe(&mut *tx))
        .await?;
    let next = change(&decode(row.as_ref())?).map_err(|error| {
        match error.downcast::<IdentityError>() {
            Ok(identity) => identity,
            Err(error) => IdentityError::Internal(error),
        }
    })?;
    write(db, &mut tx, &next).await?;
    crate::runtime::audit(db, &mut tx, actor, "login.providers.save", audit(&next)).await?;
    tx.commit().await?;
    Ok(summary(next))
}

async fn write(db: &Database, tx: &mut Tx<'_>, stored: &Stored) -> Result<()> {
    db::query("INSERT INTO gonof_common_settings(skey,svalue) VALUES(?,?) ON DUPLICATE KEY UPDATE svalue=VALUES(svalue)")
        .bind(SETTING)
        .bind(serde_json::to_string(stored)?)
        .execute(db.observe(&mut **tx))
        .await?;
    Ok(())
}

/// One code to be sent.
pub struct Message<'a> {
    /// Id of the code record: the local file name and the external serial number at Alibaba Cloud.
    pub id: i64,
    /// E.164, +86 only.
    pub mobile: &'a str,
    pub code: &'a str,
    pub ttl_minutes: i64,
    /// `login` / `bind` / `confirm`, written only into the local file.
    pub purpose: &'a str,
}

/// Why delivery failed: the first two can be told to the member, the rest are only logged.
#[derive(Debug)]
pub enum DeliveryError {
    /// The provider rate-limits or applies a daily limit per number.
    Frequent,
    /// The provider considers the number incorrect.
    InvalidNumber,
    Failed(anyhow::Error),
}

impl From<anyhow::Error> for DeliveryError {
    fn from(error: anyhow::Error) -> Self {
        Self::Failed(error)
    }
}

/// Sends one code. `directory` is the local private directory
/// ([`crate::identity::Identity::private_directory`]).
pub async fn deliver(
    db: &Database,
    config: &CommonConfig,
    directory: &Path,
    message: &Message<'_>,
) -> std::result::Result<(), DeliveryError> {
    let stored = stored(db).await?;
    if stored.sms.transport != "aliyun" {
        return deliver_local(directory, message).await.map_err(Into::into);
    }
    let secret = decrypt(config, &stored.sms_secret, &stored.sms.context())?;
    send_aliyun(&stored.sms, &secret, message).await
}

/// The folder local delivery writes into, under the local private directory
/// ([`crate::identity::Identity::private_directory`]).
pub fn local_folder(private_directory: &Path) -> PathBuf {
    private_directory.join("sms")
}

/// The local file of one code in [`local_folder`], named by the id of its code row.
pub fn local_file(folder: &Path, id: i64) -> PathBuf {
    folder.join(format!("{id}.txt"))
}

/// Local delivery: one file `sms/{id}.txt` per code; tests read the codes from here.
async fn deliver_local(directory: &Path, message: &Message<'_>) -> Result<()> {
    let folder = local_folder(directory);
    tokio::fs::create_dir_all(&folder)
        .await
        .with_context(|| format!("cannot create the local SMS directory {}", folder.display()))?;
    let body = format!(
        "{}\n",
        crate::i18n::current().account_sms_local_file(
            message.mobile,
            message.purpose,
            message.code,
            message.ttl_minutes,
        )
    );
    tokio::fs::write(local_file(&folder, message.id), body)
        .await
        .context("failed to write the SMS to the local directory")
}

async fn send_aliyun(
    provider: &SmsProvider,
    secret: &str,
    message: &Message<'_>,
) -> std::result::Result<(), DeliveryError> {
    let national = message
        .mobile
        .strip_prefix("+86")
        .ok_or(DeliveryError::InvalidNumber)?;
    let template =
        serde_json::json!({"code": message.code, "min": message.ttl_minutes.to_string()})
            .to_string();
    let out_id = message.id.to_string();
    let params = [
        ("CountryCode", "86"),
        ("OutId", out_id.as_str()),
        ("PhoneNumber", national),
        ("SignName", provider.sign_name.as_str()),
        ("TemplateCode", provider.template_code.as_str()),
        ("TemplateParam", template.as_str()),
    ];
    let query = canonical_query(&params);
    let date = chrono::DateTime::from_timestamp(crate::identity::now(), 0)
        .ok_or_else(|| anyhow!("invalid system time"))?
        .format("%Y-%m-%dT%H:%M:%SZ")
        .to_string();
    let mut nonce = [0_u8; 16];
    OsRng.fill_bytes(&mut nonce);
    let headers = [
        ("host", ALIYUN_HOST.to_owned()),
        ("x-acs-action", ALIYUN_ACTION.to_owned()),
        ("x-acs-content-sha256", EMPTY_SHA256.to_owned()),
        ("x-acs-date", date),
        ("x-acs-signature-nonce", hex(&nonce)),
        ("x-acs-version", ALIYUN_VERSION.to_owned()),
    ];
    let authorization = authorization(
        "POST",
        &query,
        &headers,
        EMPTY_SHA256,
        &provider.access_key_id,
        secret,
    );
    let mut request = crate::outbound::Request::builder()
        .method(crate::outbound::Method::POST)
        .uri(format!("https://{ALIYUN_HOST}/?{query}"))
        .header(crate::outbound::header::ACCEPT, "application/json")
        .header(crate::outbound::header::AUTHORIZATION, authorization);
    for (name, value) in &headers {
        if *name != "host" {
            request = request.header(*name, value);
        }
    }
    let request = request
        .body(Full::new(Bytes::new()))
        .context("failed to build the Alibaba Cloud request")?;
    let response = crate::outbound::send(request, ALIYUN_TIMEOUT, RESPONSE_LIMIT).await?;
    #[derive(Deserialize)]
    struct Reply {
        #[serde(rename = "Code", default)]
        code: String,
        #[serde(rename = "Message", default)]
        message: String,
    }
    let reply: Reply = serde_json::from_slice(&response.body).map_err(|_| {
        anyhow!(
            "Alibaba Cloud SMS returned an unrecognized response (HTTP {})",
            response.status
        )
    })?;
    match classify(&reply.code) {
        Some(outcome) => outcome,
        None => Err(DeliveryError::Failed(anyhow!(
            "Alibaba Cloud SMS failed to send (HTTP {}): {} {}",
            response.status,
            reply.code,
            reply.message
        ))),
    }
}

/// Classification of Alibaba Cloud return codes. The codes for rate limiting and wrong numbers also come in
/// prefixed forms (the test site actually received `biz.FREQUENCY` on 2026-11-07), so they are matched by
/// keyword.
fn classify(code: &str) -> Option<std::result::Result<(), DeliveryError>> {
    if code == "OK" {
        Some(Ok(()))
    } else if code.contains("FREQUENCY") || code.contains("LIMIT_CONTROL") {
        Some(Err(DeliveryError::Frequent))
    } else if code.contains("MOBILE_NUMBER_ILLEGAL") {
        Some(Err(DeliveryError::InvalidNumber))
    } else {
        None
    }
}

/// Canonical query string: parameter names sorted by character order, names and values encoded per RFC 3986.
fn canonical_query(params: &[(&str, &str)]) -> String {
    let mut sorted: Vec<_> = params.to_vec();
    sorted.sort_by(|a, b| a.0.cmp(b.0));
    sorted
        .iter()
        .map(|(name, value)| {
            format!(
                "{}={}",
                utf8_percent_encode(name, RFC3986),
                utf8_percent_encode(value, RFC3986)
            )
        })
        .collect::<Vec<_>>()
        .join("&")
}

/// The `Authorization` header of Alibaba Cloud V3 signing. `headers` are the headers to sign (lower-case names,
/// sorted by name); the path of RPC APIs is `/`.
fn authorization(
    method: &str,
    query: &str,
    headers: &[(&str, String)],
    payload_hash: &str,
    access_key_id: &str,
    secret: &str,
) -> String {
    let (canonical, signed) = canonical_request(method, query, headers, payload_hash);
    let to_sign = format!(
        "ACS3-HMAC-SHA256\n{}",
        hex(&Sha256::digest(canonical.as_bytes()))
    );
    let mut mac =
        <Hmac<Sha256> as Mac>::new_from_slice(secret.as_bytes()).expect("HMAC accepts any key");
    mac.update(to_sign.as_bytes());
    format!(
        "ACS3-HMAC-SHA256 Credential={access_key_id},SignedHeaders={signed},Signature={}",
        hex(&mac.finalize().into_bytes())
    )
}

fn canonical_request(
    method: &str,
    query: &str,
    headers: &[(&str, String)],
    payload_hash: &str,
) -> (String, String) {
    let mut sorted: Vec<_> = headers.to_vec();
    sorted.sort_by(|a, b| a.0.cmp(b.0));
    let lines: String = sorted
        .iter()
        .map(|(name, value)| format!("{name}:{}\n", value.trim()))
        .collect();
    let signed = sorted
        .iter()
        .map(|(name, _)| *name)
        .collect::<Vec<_>>()
        .join(";");
    (
        format!("{method}\n/\n{query}\n{lines}\n{signed}\n{payload_hash}"),
        signed,
    )
}

fn hex(bytes: &[u8]) -> String {
    use std::fmt::Write as _;
    bytes.iter().fold(String::new(), |mut out, byte| {
        let _ = write!(out, "{byte:02x}");
        out
    })
}

