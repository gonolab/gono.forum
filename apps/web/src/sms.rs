    #[test]
    fn saving_keeps_or_requires_the_secret() {
        let config = CommonConfig {
            encryption_key: "02".repeat(32),
        };
        let aliyun = SmsProvider {
            transport: "aliyun".into(),
            access_key_id: "LTAIexample".into(),
            sign_name: "Sample Sign".into(),
            template_code: "100001".into(),
            has_secret: false,
        };
        let empty = Stored::default();
        let input = |secret: &str, revision: i64, sms: &SmsProvider| SmsInput {
            revision,
            sms: sms.clone(),
            secret: secret.into(),
        };
        assert!(candidate(&config, input("", 0, &aliyun), &empty).is_err());
        let saved = candidate(&config, input("k", 0, &aliyun), &empty).unwrap();
        assert_eq!(saved.revision, 1);
        let kept = candidate(&config, input("", 1, &aliyun), &saved).unwrap();
        assert_eq!(kept.sms_secret, saved.sms_secret);
        let moved = SmsProvider {
            access_key_id: "LTAIother".into(),
            ..aliyun.clone()
        };
        assert!(candidate(&config, input("", 1, &moved), &saved).is_err());
        assert!(
            candidate(&config, input("", 0, &aliyun), &saved).is_err(),
            "the revision does not match"
        );
        let local = SmsProvider::default();
        assert!(candidate(&CommonConfig::default(), input("", 0, &local), &empty).is_ok());
    }

    #[test]
    fn oauth_credentials_save_separately_from_sms() {
        let config = CommonConfig {
            encryption_key: "02".repeat(32),
        };
        let input = |client_id: &str, secret: &str, revision: i64| OAuthInput {
            revision,
            provider: Provider::Github,
            client_id: client_id.into(),
            secret: secret.into(),
        };
        let start = Stored {
            sms_secret: vec![1, 2, 3],
            ..Default::default()
        };
        assert!(
            oauth_candidate(&config, input("Iv23li", "", 0), &start).is_err(),
            "the first save needs a secret"
        );
        assert!(oauth_candidate(&config, input("has space", "s", 0), &start).is_err());
        let saved = oauth_candidate(&config, input("Iv23li", "github-secret", 0), &start).unwrap();
        assert_eq!(
            saved.sms_secret,
            vec![1, 2, 3],
            "the SMS part is kept as is"
        );
        assert!(saved.google_secret.is_empty());
        assert_eq!(
            config
                .open(
                    &saved.github_secret,
                    &oauth_context(Provider::Github, "Iv23li")
                )
                .as_deref(),
            Some("github-secret")
        );
        assert!(
            config
                .open(
                    &saved.github_secret,
                    &oauth_context(Provider::Google, "Iv23li")
                )
                .is_none(),
            "the ciphertext is bound to the provider"
        );
        let kept = oauth_candidate(&config, input("Iv23li", "", 1), &saved).unwrap();
        assert_eq!(kept.github_secret, saved.github_secret);
        assert!(oauth_candidate(&config, input("Iv23other", "", 1), &saved).is_err());
        let cleared = oauth_candidate(&config, input("", "", 1), &saved).unwrap();
        assert!(cleared.github.client_id.is_empty() && cleared.github_secret.is_empty());
        assert!(
            oauth_candidate(&CommonConfig::default(), input("Iv23li", "s", 0), &start).is_err(),
            "nothing is saved without an encryption key"
        );
        let sms_after = candidate(
            &config,
            SmsInput {
                revision: 1,
                sms: SmsProvider::default(),
                secret: String::new(),
            },
            &saved,
        )
        .unwrap();
        assert_eq!(
            sms_after.github_secret, saved.github_secret,
            "saving SMS leaves GitHub alone"
        );
    }
