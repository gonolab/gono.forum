    /// The example from the Alibaba Cloud V3 signing docs (fixed key, time and nonce): the computed digest and
    /// signature must match the docs.
    #[test]
    fn v3_signature_matches_the_documented_example() {
        let query = canonical_query(&[
            ("RegionId", "cn-shanghai"),
            (
                "ImageId",
                "win2019_1809_x64_dtc_zh-cn_40G_alibase_20230811.vhd",
            ),
        ]);
        assert_eq!(
            query,
            "ImageId=win2019_1809_x64_dtc_zh-cn_40G_alibase_20230811.vhd&RegionId=cn-shanghai"
        );
        let headers = [
            ("x-acs-version", "2014-05-26".to_owned()),
            ("host", "ecs.cn-shanghai.aliyuncs.com".to_owned()),
            ("x-acs-action", "RunInstances".to_owned()),
            ("x-acs-content-sha256", EMPTY_SHA256.to_owned()),
            ("x-acs-date", "2023-10-26T10:22:32Z".to_owned()),
            (
                "x-acs-signature-nonce",
                "3156853299f313e23d1673dc12e1703d".to_owned(),
            ),
        ];
        let (canonical, signed) = canonical_request("POST", &query, &headers, EMPTY_SHA256);
        assert_eq!(
            signed,
            "host;x-acs-action;x-acs-content-sha256;x-acs-date;x-acs-signature-nonce;x-acs-version"
        );
        assert_eq!(
            hex(&Sha256::digest(canonical.as_bytes())),
            "7ea06492da5221eba5297e897ce16e55f964061054b7695beedaac1145b1e259"
        );
        assert_eq!(
            authorization(
                "POST",
                &query,
                &headers,
                EMPTY_SHA256,
                "YourAccessKeyId",
                "YourAccessKeySecret"
            ),
            "ACS3-HMAC-SHA256 Credential=YourAccessKeyId,SignedHeaders=host;x-acs-action;x-acs-content-sha256;x-acs-date;x-acs-signature-nonce;x-acs-version,Signature=06563a9e1b43f5dfe96b81484da74bceab24a1d853912eee15083a6f0f3283c0"
        );
    }

