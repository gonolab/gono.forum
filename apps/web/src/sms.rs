//! SMS delivery. Codes are generated, stored as digests and checked by [`crate::identity`]; this module only gets them
//! to the phone.
//!
//! - The provider configuration is stored in the [`SETTING`] row of `gonof_common_settings` (one JSON value,
//!   not seeded, inserted on the first save, like `mail.transport`).
//!   The AccessKey Secret is encrypted with the private config `[common] encryption_key` (the same key as the
//!   mail authorization code), with the AccessKey ID bound as associated data:
//!   changing the ID directly in the database makes it undecryptable.
//! - Delivery methods: `local` writes into `sms/` in the local private directory (the default when no provider is
//!   configured, for development and testing; members receive nothing). Each file holds the number and the code in
//!   plain text: the retention cleanup removes it together with its code row and sweeps up any file older than the
//!   code retention period ([`crate::maintenance`]), and account deletion removes the files of the codes sent to the
//!   member's number. `aliyun` calls `SendSmsVerifyCode` of the Alibaba Cloud phone number verification service
//!   "SMS Authentication", using the platform's preset signature and template, with the code generated by this site
//!   passed directly as the template parameter (allowed by the Alibaba Cloud docs; this site then does the checking).
//!   Requests use Alibaba Cloud V3 signing (ACS3-HMAC-SHA256).
//! - Google and GitHub credentials are stored in this row too: the Client ID in plain text, the
//!   Client Secret likewise encrypted, with the provider and Client ID bound as associated data.
//!   Each save changes only its own section and keeps the rest as is; the JSON does not reject unknown fields.
